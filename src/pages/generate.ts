// ── Fonts ──

const STYLE_BLURBS: Record<FontStyle, string> = {
  classic: "Unicode's own bold, italic, sans-serif, monospace and wide letters. The most readable choice, and the only fonts with real bold and italic.",
  script: "Handwriting-style letters, in regular and bold.",
  gothic: "Blackletter, the old German style also called Fraktur, in regular and bold.",
  outline: "Double-struck letters, the hollow style used in maths for ℝ and ℕ.",
  boxed: "Letters in circles or squares, filled or outlined.",
  small: "Small capitals, and letters raised or lowered like footnotes.",
  marked: "Ordinary letters with a line, slash, tilde or mark through, under or around each one.",
  lookalike: "Letters borrowed from other alphabets, such as Tai Viet, Yi and Greek, chosen because they look like ours. Playful, but the hardest to read.",
};

const VARIANTS: { key: "regular" | "bold" | "italic" | "boldItalic"; label: string; bold: boolean; italic: boolean }[] = [
  { key: "regular", label: "", bold: false, italic: false },
  { key: "bold", label: "Bold", bold: true, italic: false },
  { key: "italic", label: "Italic", bold: false, italic: true },
  { key: "boldItalic", label: "Bold italic", bold: true, italic: true },
];

function fontRows(font: UiFont): string {
  return VARIANTS.filter((v) => v.key === "regular" || font[v.key])
    .map((v) => {
      // Serif's regular face is the plain text itself, shown in the page's own font
      const base = font.id === "serif" && v.key === "regular" ? "Plain text (no change)" : font.label;
      const name = v.label ? `${font.label} ${v.label.toLowerCase()}` : base;
      const sample = renderSample(font.id, DEFAULT_SAMPLE, v.bold, v.italic);
      return `            <li class="fx-row">
              <span class="fx-name">${esc(name)}</span>
              <span class="fx-sample" data-font="${font.id}" data-bold="${v.bold}" data-italic="${v.italic}">${esc(sample)}</span>
              <button type="button" class="fx-copy" data-copy-from="prev" aria-label="Copy in ${esc(name)}">Copy</button>
            </li>`;
    })
    .join("\n");
}

function fontsPage(): GeneratedPage {
  const count = ALL_UI_FONTS.length;
  const groups = FONT_STYLES.map((s) => {
    const fonts = ALL_UI_FONTS.filter((f) => f.style === s.id);
    return `      <section class="step ref-group" id="${s.id}">
        <div>
          <h2>${esc(s.label)} <small class="ref-count">${fonts.length}</small></h2>
          <p>${esc(STYLE_BLURBS[s.id])}</p>
          <ul class="fx-list">
${fonts.map(fontRows).join("\n")}
          </ul>
        </div>
      </section>`;
  }).join("\n");

  const body = `${head(
    "Fonts",
    `Fonts for <em>Instagram</em>, to copy and paste`,
    `All ${count} fonts from InstaStylr, showing your own words. Type below, then copy the one you like and paste it into a caption, a bio, a YouTube description or a LinkedIn post.`,
  )}
      <div class="fx-input">
        <label for="fx-text">Your text</label>
        <input id="fx-text" type="text" value="${DEFAULT_SAMPLE}" maxlength="120" autocomplete="off" spellcheck="false" />
      </div>
      <nav class="ref-jump" aria-label="Font styles">
${FONT_STYLES.map((s) => `        <a href="#${s.id}">${esc(s.label)}</a>`).join("\n")}
      </nav>
${groups}
      <section class="step">
        <div>
          <h2>Before you use them everywhere</h2>
          <p>These aren't fonts in the usual sense. Each letter is swapped for a different Unicode character that looks like a styled letter, which is why the style survives pasting. Two things follow from that:</p>
          <ul>
            <li><strong>Screen readers may not read them.</strong> Some read each letter as a maths symbol, some skip it. Keep names, prices and anything important in plain text, and style a word or a heading rather than the whole post.</li>
            <li><strong>Search can't find them.</strong> A styled word in your bio or caption won't match a search for the plain word, so keep keywords and hashtags plain.</li>
          </ul>
          <p>Characters a font has no version of, such as accented letters or punctuation, are left as they are.</p>
        </div>
      </section>`;

  return {
    file: "fonts/index.html",
    html: page({
      path: "/fonts/",
      dataPage: "fonts",
      title: `Instagram fonts: ${count} styles to copy and paste · InstaStylr`,
      description: `${count} fonts for Instagram captions and bios: bold, italic, cursive, gothic, bubble, small caps and more. Type your text, copy, paste. Free.`,
      crumbs: [{ name: "Fonts", path: "/fonts/" }],
      body,
    }),
  };
}

// ── Bullets ──

function bulletsPage(): GeneratedPage {
  const categories = BULLET_CATEGORY_FILTERS.filter((c) => c !== "all");
  const total = new Set(BULLET_PRESETS.map(bulletPresetMarker)).size;
  const groups = categories
    .map((c) => {
      const presets = BULLET_PRESETS.filter((p) => p.category === c);
      const chips = presets
        .map((p) => {
          const text = p.kind === "single" ? p.marker : `${p.main} ${p.sub}`;
          const label = p.kind === "single" ? `Copy ${p.marker}` : `Copy the pair ${p.main} and ${p.sub}`;
          return `            <li><button type="button" class="sym" data-copy="${esc(text)}" aria-label="${esc(label)}">${esc(p.kind === "single" ? p.marker : `${p.main} ${p.sub}`)}</button></li>`;
        })
        .join("\n");
      const note =
        c === "nested"
          ? `<p>Pairs for a list inside a list: the first for the main items, the second for the items under them.</p>\n`
          : "";
      return `      <section class="step ref-group" id="${c}">
        <div>
          <h2>${esc(BULLET_CATEGORY_LABELS[c])} <small class="ref-count">${presets.length}</small></h2>
          ${note}<ul class="sym-grid">
${chips}
          </ul>
        </div>
      </section>`;
    })
    .join("\n");

  const body = `${head(
    `Symbols · Bullets`,
    `Bullet point symbols <em>to copy</em>`,
    `${total} bullets for Instagram captions and bios: dots, stars, flowers, hearts, arrows and more. Tap one to copy it, then paste it at the start of a line.`,
  )}
      <nav class="ref-jump" aria-label="Bullet groups">
${categories.map((c) => `        <a href="#${c}">${esc(BULLET_CATEGORY_LABELS[c])}</a>`).join("\n")}
      </nav>
${groups}
      <section class="step">
        <div>
          <h2>Making a whole list</h2>
          <p>Pasting a bullet in front of every line works, but it gets slow. In <a href="/app/?theme=dark&amp;from=symbols-bullets-tip">InstaStylr</a> you make a real list, choose any of these bullets for it, and press <kbd>Tab</kbd> to put items under others. <a href="/learn/lists/">The lists tutorial</a> shows how, step by step.</p>
          <p>Emoji bullets such as 🌸 look different on each phone. The plain symbols look the same everywhere.</p>
        </div>
      </section>`;

  return {
    file: "symbols/bullets/index.html",
    html: page({
      path: "/symbols/bullets/",
      dataPage: "symbols-bullets",
      title: "Bullet point symbols for Instagram, to copy and paste · InstaStylr",
      description: `${total} bullet point symbols for Instagram captions and bios: dots, stars, flowers, hearts and arrows. Tap to copy, then paste. Free.`,
      crumbs: [{ name: "Bullet symbols", path: "/symbols/bullets/" }],
      body,
    }),
  };
}

// ── Dividers ──

const DIVIDER_ORDER: DividerCategory[] = [
  "simple", "spaced", "grouped", "unicode", "accent", "triple",
  "bookend", "motif", "frames", "borders", "patterns", "aesthetic",
];

function dividersPage(): GeneratedPage {
  const seen = new Set<string>();
  const unique = DIVIDER_PRESETS.filter((d) => !seen.has(d.line) && Boolean(seen.add(d.line)));
  const used = DIVIDER_ORDER.filter((c) => unique.some((d) => d.category === c));
  const groups = used
    .map((c) => {
      const lines = unique.filter((d) => d.category === c);
      return `      <section class="step ref-group" id="${c}">
        <div>
          <h2>${esc(DIVIDER_CATEGORY_LABELS[c])} <small class="ref-count">${lines.length}</small></h2>
          <ul class="div-list">
${lines.map((d) => `            <li><button type="button" class="div-line" data-copy="${esc(d.line)}" aria-label="Copy divider ${esc(d.line)}">${esc(d.line)}</button></li>`).join("\n")}
          </ul>
        </div>
      </section>`;
    })
    .join("\n");

  const body = `${head(
    `Symbols · Dividers`,
    `Divider lines <em>for captions</em>`,
    `${unique.length} ready-made dividers for Instagram captions, made of ordinary characters so they paste anywhere. Tap one to copy it, then paste it between two parts of your caption.`,
  )}
      <nav class="ref-jump" aria-label="Divider groups">
${used.map((c) => `        <a href="#${c}">${esc(DIVIDER_CATEGORY_LABELS[c])}</a>`).join("\n")}
      </nav>
${groups}
      <section class="step">
        <div>
          <h2>Making your own</h2>
          <p>Every line here comes from the divider editor in <a href="/app/?theme=dark&amp;from=symbols-dividers-tip">InstaStylr</a>, where you can change the character, the length and the ornament in the middle, and see it in your caption as you go. <a href="/learn/dividers/">The dividers tutorial</a> walks through it.</p>
          <p>Long dividers can wrap onto a second line on narrow phones. Around 10 to 15 characters is safe for Instagram.</p>
        </div>
      </section>`;

  return {
    file: "symbols/dividers/index.html",
    html: page({
      path: "/symbols/dividers/",
      dataPage: "symbols-dividers",
      title: "Instagram caption dividers, to copy and paste · InstaStylr",
      description: `${unique.length} divider lines for Instagram captions: simple rules, stars, flowers, frames and borders. Tap to copy, then paste between paragraphs. Free.`,
      crumbs: [{ name: "Dividers", path: "/symbols/dividers/" }],
      body,
    }),
  };
}

export function generatePages(): GeneratedPage[] {
  return [fontsPage(), bulletsPage(), dividersPage()];
}
